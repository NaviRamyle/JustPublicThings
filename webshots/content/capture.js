// Walks the live page and builds a cleaned tree of what is on screen: visible
// elements only, live form values, shadow DOM flattened, secrets removed.
// render.js turns that tree into Text, HTML or HTML + CSS.
(() => {
  const W = (globalThis.Webshots ||= {});
  if (W.capture) return;

  const MAX_ELEMENTS = 20000;
  const SKIP_TAGS = new Set(['script', 'style', 'noscript', 'template', 'link', 'meta', 'head', 'title', 'base', 'source', 'track', 'param']);
  const FIELDS = new Set(['input', 'select', 'textarea']);
  // Leaf-like elements the walker doesn't descend into when looking for a region's root
  const LEAVES = new Set(['img', 'svg', 'canvas', 'video', 'audio', 'iframe', 'embed', 'object', 'input', 'textarea', 'select']);
  // Elements whose size is their own (not "fill the parent"), so width/height are worth keeping
  const SIZED = new Set([...LEAVES, 'button']);
  const KEEP_ATTRS = new Set([
    'id', 'class', 'href', 'src', 'alt', 'title', 'type', 'name', 'value', 'placeholder', 'role', 'for',
    'colspan', 'rowspan', 'scope', 'start', 'datetime', 'lang', 'dir', 'action', 'method', 'min', 'max', 'step',
    'disabled', 'readonly', 'required', 'multiple', 'open',
    'data-testid', 'data-test', 'data-test-id', 'data-cy', 'data-qa',
  ]);
  const BOOL_ATTRS = new Set(['disabled', 'readonly', 'required', 'multiple', 'open']);
  const TABLE_SELECTOR = 'table, [role=grid], [role=table], [role=treegrid]';
  const TABLE_ROLE = /^(grid|table|treegrid)$/;

  // Class names generated by CSS-in-JS and CSS modules carry no meaning
  const HASHED_CLASS = /^(css|jsx|svelte|emotion)-[\w-]*\d[\w-]*$|^sc-[a-z]+$|^[a-z][\w-]*_[\w-]+__[\w-]{5}$/i;
  const SECRET_PARAM = /token|secret|session|passw(or)?d|pwd|api[-_]?key|access[-_]?key|credential|signature|saml|^(code|state|sig|sid|jwt|auth|key|ticket|nonce|otp|x-amz-[\w-]+)$/i;
  const SECRET_FIELD = /passw|passcode|secret|token|otp|cvv|cvc|ssn|(^|[_-])pin$|card.?num|cc-?num/i;
  const SECRET_AUTOCOMPLETE = /password|one-time-code|cc-number|cc-csc/i;

  // CSS properties that affect how things look. Inherited ones are compared with the
  // parent, the rest with the browser default for that tag.
  const PROPS = [
    'display', 'position', 'top', 'right', 'bottom', 'left', 'z-index', 'float',
    'width', 'height', 'min-width', 'min-height', 'max-width', 'max-height',
    'margin-top', 'margin-right', 'margin-bottom', 'margin-left',
    'padding-top', 'padding-right', 'padding-bottom', 'padding-left',
    'border-top-width', 'border-right-width', 'border-bottom-width', 'border-left-width',
    'border-top-style', 'border-right-style', 'border-bottom-style', 'border-left-style',
    'border-top-color', 'border-right-color', 'border-bottom-color', 'border-left-color',
    'border-top-left-radius', 'border-top-right-radius', 'border-bottom-right-radius', 'border-bottom-left-radius',
    'border-collapse', 'background-color', 'background-image',
    'color', 'font-family', 'font-size', 'font-weight', 'font-style', 'line-height', 'letter-spacing',
    'text-align', 'text-transform', 'text-decoration-line', 'text-overflow', 'white-space', 'vertical-align',
    'opacity', 'visibility', 'overflow-x', 'overflow-y', 'box-shadow', 'transform',
    'flex-direction', 'flex-wrap', 'justify-content', 'align-items', 'align-self', 'align-content',
    'flex-grow', 'flex-shrink', 'flex-basis', 'order', 'row-gap', 'column-gap',
    'grid-template-columns', 'grid-template-rows', 'grid-column-start', 'grid-column-end', 'grid-row-start', 'grid-row-end',
    'list-style-type', 'object-fit', 'cursor',
  ];
  const INHERITED = new Set([
    'color', 'font-family', 'font-size', 'font-weight', 'font-style', 'line-height', 'letter-spacing',
    'text-align', 'text-transform', 'white-space', 'visibility', 'list-style-type', 'cursor', 'border-collapse',
  ]);
  // vertical-align isn't inherited, but table cells get it from their row
  const CELL_PARTS = new Set(['tr', 'td', 'th']);
  // Form controls don't inherit fonts and colors from the page by default
  const CONTROLS = new Set(['input', 'select', 'textarea', 'button']);
  const SIDES = ['top', 'right', 'bottom', 'left'];
  const CORNERS = ['top-left', 'top-right', 'bottom-right', 'bottom-left'];

  // ---------- URLs and secrets ----------

  function cleanUrl(raw, base = location.href) {
    if (!raw) return '';
    if (/^\s*data:/i.test(raw)) return 'data:…';
    if (/^\s*javascript:/i.test(raw)) return '';
    let url;
    try { url = new URL(raw, base); } catch { return raw; }
    if (!/^(https?|file):$/.test(url.protocol)) return url.href;
    url.username = url.password = '';
    const tail = url.search + url.hash;
    const head = url.href.slice(0, url.href.length - tail.length);
    return head + tail.replace(/([?&#])([^=&#?]+)=([^&#]*)/g, (m, sep, key, val) => {
      let name = key;
      try { name = decodeURIComponent(key); } catch {}
      return val && SECRET_PARAM.test(name) ? `${sep}${key}=REDACTED` : m;
    });
  }

  const isSecretField = el =>
    el.type === 'password' ||
    SECRET_AUTOCOMPLETE.test(el.getAttribute('autocomplete') || '') ||
    SECRET_FIELD.test(el.name || '') ||
    SECRET_FIELD.test(el.id || '');

  function cleanAttrs(el, tag) {
    const out = {};
    const field = FIELDS.has(tag) || tag === 'option';
    for (const { name, value } of el.attributes) {
      if (!name.startsWith('aria-') && !KEEP_ATTRS.has(name)) continue;
      if (field && name === 'value') continue; // the live value is read separately
      let v = value;
      if (name === 'class') v = value.split(/\s+/).filter(c => c && !HASHED_CLASS.test(c)).join(' ');
      else if (name === 'href' || name === 'action') v = value.startsWith('#') ? value : cleanUrl(value, el.baseURI);
      else if (name === 'src') v = cleanUrl((tag === 'img' && el.currentSrc) || value, el.baseURI);
      if (v || BOOL_ATTRS.has(name)) out[name] = v;
    }
    return out;
  }

  // ---------- Element details ----------

  function fieldLabel(el) {
    const ids = el.getAttribute('aria-labelledby');
    if (ids) {
      const root = el.getRootNode();
      const text = ids.split(/\s+/).map(id => root.getElementById?.(id)?.textContent || '').join(' ').trim();
      if (text) return text.replace(/\s+/g, ' ');
    }
    const label = el.getAttribute('aria-label') || el.labels?.[0]?.innerText || el.placeholder || el.title || el.name || '';
    return label.replace(/\s+/g, ' ').trim();
  }

  function fieldInfo(el, tag) {
    const type = tag === 'input' ? el.type : tag;
    const info = { type, label: fieldLabel(el), hasLabelEl: !!el.labels?.length };
    if (type === 'checkbox' || type === 'radio') {
      info.checked = el.checked;
    } else if (tag === 'select') {
      const opts = [...el.options];
      info.value = opts.filter(o => o.selected).map(o => o.text.trim()).join(', ');
      info.options = opts.slice(0, 50).map(o => ({ text: o.text.trim(), value: o.value, selected: o.selected }));
      info.moreOptions = Math.max(0, opts.length - 50);
    } else if (type !== 'file') {
      info.value = el.value;
    }
    if (info.value && isSecretField(el)) info.value = '••••••';
    return info;
  }

  function svgInfo(el) {
    const texts = [...el.querySelectorAll('text')]
      .map(t => t.textContent.replace(/\s+/g, ' ').trim())
      .filter(Boolean)
      .slice(0, 300);
    const title = el.querySelector(':scope > title')?.textContent || '';
    return { texts, label: (el.getAttribute('aria-label') || title).trim() };
  }

  function shadowOf(el) {
    if (el.shadowRoot) return el.shadowRoot;
    try {
      return globalThis.chrome?.dom?.openOrClosedShadowRoot?.(el) || null;
    } catch {
      return null;
    }
  }

  // Children as rendered: a shadow root replaces the light DOM, a slot shows what is assigned to it
  function childNodesOf(el) {
    const sr = shadowOf(el);
    if (sr) return sr.childNodes;
    if (el.localName === 'slot') {
      const assigned = el.assignedNodes({ flatten: true });
      if (assigned.length) return assigned;
    }
    return el.childNodes;
  }

  // "Screen reader only" text and transparent elements aren't visible
  function isVisuallyHidden(cs, rect) {
    if (cs.opacity === '0') return true;
    return rect.width <= 1 && rect.height <= 1 && (cs.overflow !== 'visible' || cs.clip !== 'auto' || cs.clipPath !== 'none');
  }

  const isTableLike = (el, tag) => tag === 'table' || TABLE_ROLE.test(el.getAttribute('role') || '');

  // Header rows are kept when any part of their table is selected, even if scrolled out of view
  function isHeaderish(el) {
    if (el.matches('thead, th, [role=columnheader]')) return true;
    return !!el.querySelector('th, [role=columnheader]') && !el.querySelector('td, [role=gridcell], [role=cell], [role=rowheader]');
  }

  // ---------- Geometry ----------

  const contains = (o, r, xOnly) =>
    r.left >= o.left - 1 && r.right <= o.right + 1 && (xOnly || (r.top >= o.top - 1 && r.bottom <= o.bottom + 1));
  const intersects = (o, r, xOnly) =>
    r.left < o.right && r.right > o.left && (xOnly || (r.top < o.bottom && r.bottom > o.top));
  const spills = el => el.scrollHeight > el.clientHeight + 1 || el.scrollWidth > el.clientWidth + 1;
  const intersect = (a, b) => ({
    left: Math.max(a.left, b.left),
    top: Math.max(a.top, b.top),
    right: Math.min(a.right, b.right),
    bottom: Math.min(a.bottom, b.bottom),
  });

  function textInRegion(node, clip, xOnly) {
    const range = node.ownerDocument.createRange();
    range.selectNodeContents(node);
    for (const r of range.getClientRects()) if (r.width > 0 && intersects(clip, r, xOnly)) return true;
    return false;
  }

  function overlaps(node, region) {
    if (node.nodeType === Node.TEXT_NODE) return !!node.data.trim() && textInRegion(node, region);
    if (node.nodeType !== Node.ELEMENT_NODE || node === W.overlayHost) return false;
    const r = node.getBoundingClientRect();
    if (r.width === 0 || r.height === 0) return getComputedStyle(node).display === 'contents';
    return intersects(region, r);
  }

  // The smallest element that holds everything in the region (or the table it's inside)
  function regionRoot(region) {
    let el = document.body;
    for (;;) {
      const hits = [...childNodesOf(el)].filter(n => overlaps(n, region));
      if (hits.length !== 1 || hits[0].nodeType !== Node.ELEMENT_NODE || LEAVES.has(hits[0].localName)) break;
      el = hits[0];
    }
    return el.closest?.(TABLE_SELECTOR) || el;
  }

  // ---------- Styles ----------

  function readVals(cs) {
    const vals = {};
    for (const p of PROPS) vals[p] = cs.getPropertyValue(p);
    return vals;
  }

  // Browser default styles per tag (and input type, and link vs. plain <a>), read from a blank iframe
  function defaultStyles() {
    const frame = document.createElement('iframe');
    frame.style.cssText = 'position:fixed;left:-10000px;top:0;width:10px;height:10px;border:0;visibility:hidden';
    document.documentElement.appendChild(frame);
    const cache = new Map();
    return {
      get(tag, el) {
        const type = tag === 'input' ? el.type : tag === 'a' && el.hasAttribute('href') ? 'link' : '';
        const key = `${tag}:${type}`;
        if (!cache.has(key)) {
          let vals = {};
          try {
            const e = frame.contentDocument.createElement(tag);
            if (tag === 'input') e.type = type;
            if (type === 'link') e.href = '#';
            frame.contentDocument.body.appendChild(e);
            vals = readVals(frame.contentWindow.getComputedStyle(e));
            e.remove();
          } catch {}
          cache.set(key, vals);
        }
        return cache.get(key);
      },
      dispose: () => frame.remove(),
    };
  }

  function hexColors(v) {
    return v.replace(/rgba?\(([^)]*)\)/g, (m, inner) => {
      const [r, g, b, a = 1] = inner.split(/[\s,/]+/).filter(Boolean).map(parseFloat);
      if (a === 0) return 'transparent';
      const parts = a < 1 ? [r, g, b, a * 255] : [r, g, b];
      return '#' + parts.map(n => Math.round(n).toString(16).padStart(2, '0')).join('');
    });
  }

  function short4([t, r, b, l]) {
    if (t === r && r === b && b === l) return t;
    if (t === b && r === l) return `${t} ${r}`;
    return `${t} ${r} ${b} ${l}`;
  }

  // A property is kept when it differs from what the element would get anyway: the browser
  // default for its tag, or for inherited properties the parent's value (unless the browser
  // sets that property for this tag, like bold <th> or blue links)
  function diffStyles(tag, vals, parent, own, neutral) {
    const changed = new Set();
    for (const p of PROPS) {
      let base = own[p];
      if (p === 'vertical-align') base = CELL_PARTS.has(tag) && parent ? parent[p] : own[p];
      else if (INHERITED.has(p) && parent && own[p] === neutral[p] && !CONTROLS.has(tag)) base = parent[p];
      if (vals[p] !== base) changed.add(p);
    }
    if (!SIZED.has(tag) && vals.position !== 'absolute' && vals.position !== 'fixed') {
      changed.delete('width');
      changed.delete('height');
    }
    return compress(vals, changed, own);
  }

  // Longhand properties -> shorthands (margin, padding, border, ...)
  function compress(vals, changed, defaults) {
    const out = [];
    const take = ps => ps.forEach(p => changed.delete(p));
    for (const p of PROPS) {
      if (!changed.has(p)) continue;
      const box = p.match(/^(margin|padding)-/);
      if (box) {
        const ps = SIDES.map(s => `${box[1]}-${s}`);
        out.push([box[1], short4(ps.map(q => vals[q]))]);
        take(ps);
      } else if (/^border-.*-radius$/.test(p)) {
        const ps = CORNERS.map(c => `border-${c}-radius`);
        out.push(['border-radius', short4(ps.map(q => vals[q]))]);
        take(ps);
      } else if (/^border-(top|right|bottom|left)-/.test(p)) {
        take(SIDES.flatMap(s => ['width', 'style', 'color'].map(k => `border-${s}-${k}`)));
        const side = (v, s) => {
          const style = v[`border-${s}-style`];
          return !style || style === 'none' || style === 'hidden' || v[`border-${s}-width`] === '0px'
            ? 'none'
            : `${v[`border-${s}-width`]} ${style} ${v[`border-${s}-color`]}`;
        };
        const sides = SIDES.map(s => side(vals, s));
        if (sides.every(s => s === sides[0])) {
          const hadBorder = SIDES.some(s => side(defaults, s) !== 'none');
          if (sides[0] !== 'none' || hadBorder) out.push(['border', sides[0]]);
        } else {
          SIDES.forEach((s, i) => sides[i] !== 'none' && out.push([`border-${s}`, sides[i]]));
        }
      } else if (p.startsWith('overflow-')) {
        const [x, y] = [vals['overflow-x'], vals['overflow-y']];
        out.push(['overflow', x === y ? x : `${x} ${y}`]);
        take(['overflow-x', 'overflow-y']);
      } else if (p === 'row-gap' || p === 'column-gap') {
        const [r, c] = [vals['row-gap'], vals['column-gap']];
        out.push(['gap', r === c ? r : `${r} ${c}`]);
        take(['row-gap', 'column-gap']);
      } else if (p.startsWith('flex-') && p !== 'flex-direction' && p !== 'flex-wrap') {
        out.push(['flex', `${vals['flex-grow']} ${vals['flex-shrink']} ${vals['flex-basis']}`]);
        take(['flex-grow', 'flex-shrink', 'flex-basis']);
      } else if (/^grid-(column|row)-/.test(p)) {
        const axis = p.split('-')[1];
        out.push([`grid-${axis}`, `${vals[`grid-${axis}-start`]} / ${vals[`grid-${axis}-end`]}`]);
        take([`grid-${axis}-start`, `grid-${axis}-end`]);
      } else {
        out.push([p, vals[p]]);
      }
    }
    return out
      .map(([p, v]) => [p, hexColors(v).replace(/url\("?data:[^)]*\)/g, 'url(data:…)')])
      .filter(([, v]) => v !== '');
  }

  // ---------- The walk ----------

  function walkNode(node, ctx, st, out) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (ctx.hiddenText || !node.data) return;
      if (!ctx.full && node.data.trim() && !textInRegion(node, ctx.clip, ctx.xOnly)) return;
      out.push({ text: node.data });
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      const result = walkEl(node, ctx, st);
      if (Array.isArray(result)) out.push(...result);
      else if (result) out.push(result);
    }
  }

  function walkEl(el, ctx, st) {
    if (el === W.overlayHost) return null;
    const tag = el.localName;
    if (SKIP_TAGS.has(tag) || (tag === 'input' && el.type === 'hidden')) return null;
    if (++st.count > MAX_ELEMENTS) {
      st.truncated = true;
      return null;
    }

    const cs = (el.ownerDocument.defaultView || window).getComputedStyle(el);
    const display = cs.display;
    if (display === 'none') return null;
    const contents = display === 'contents';
    const rect = contents ? null : el.getBoundingClientRect();
    if (rect) {
      if (el.checkVisibility && !el.checkVisibility()) return null;
      // Custom checkboxes often hide the real input; keep it for its checked state
      if (!FIELDS.has(tag) && isVisuallyHidden(cs, rect)) return null;
    }

    // Region selections: keep what's inside, drop what's outside, look closer at what's partly in
    let full = ctx.full;
    let xOnly = false;
    if (!full && rect) {
      if (tag === 'br' || tag === 'wbr') {
        return rect.bottom > ctx.clip.top && rect.top < ctx.clip.bottom ? { tag, attrs: {}, display, kids: [] } : null;
      }
      xOnly = ctx.inTable && isHeaderish(el);
      if (rect.width > 0 && rect.height > 0) {
        // Inside the selection only counts if the content doesn't spill out of the box
        // (scroll boxes, or a body with height: 100% on a long page)
        if (contains(ctx.clip, rect, xOnly)) full = !spills(el);
        else if (!intersects(ctx.clip, rect, xOnly)) return null;
      }
    }

    const node = { tag, attrs: cleanAttrs(el, tag), display, kids: [] };
    if (rect) node.size = [Math.round(rect.width), Math.round(rect.height)];
    if (/^(pre|pre-wrap|break-spaces)$/.test(cs.whiteSpace)) node.pre = true;
    if (display.endsWith('flex') && cs.flexDirection.startsWith('row')) {
      node.row = true;
      node.spaced = parseFloat(cs.columnGap) > 0 || cs.justifyContent.includes('space');
    }

    let vals = ctx.vals;
    if (st.defaults) {
      vals = readVals(cs);
      if (!contents) node.styles = diffStyles(tag, vals, ctx.vals, st.defaults.get(tag, el), st.defaults.get('span', el));
    }

    switch (tag) {
      case 'svg':
        node.info = svgInfo(el);
        return node;
      case 'img': case 'canvas': case 'video': case 'audio': case 'embed': case 'object':
        return node;
      case 'progress': case 'meter':
        node.info = { value: el.value, max: el.max };
        return node;
      case 'input': case 'select': case 'textarea':
        node.info = fieldInfo(el, tag);
        return node;
      case 'iframe': {
        let body = null;
        try { body = el.contentDocument?.body; } catch {}
        node.info = { crossOrigin: !body };
        if (body) walkNode(body, { full: true, vals: null }, st, node.kids);
        return node;
      }
    }

    const kidCtx = {
      full,
      clip: ctx.clip,
      xOnly,
      vals,
      hiddenText: cs.visibility !== 'visible',
    };
    if (!full && rect && (cs.overflowX !== 'visible' || cs.overflowY !== 'visible')) kidCtx.clip = intersect(ctx.clip, rect);
    kidCtx.inTable = ctx.inTable || (!full && isTableLike(el, tag));

    let hadContent = false;
    let children = childNodesOf(el);
    // A closed <details> only shows its <summary>
    if (tag === 'details' && !el.open) children = [...children].filter(c => c.localName === 'summary');
    for (const child of children) {
      if (child.nodeType === Node.ELEMENT_NODE || child.data?.trim()) hadContent = true;
      walkNode(child, kidCtx, st, node.kids);
    }

    if (!node.kids.some(k => k.tag || k.text.trim())) {
      // visibility:hidden with nothing visible inside
      if (kidCtx.hiddenText) return null;
      // Partly selected, but all of its content is outside the selection
      if (!full && (hadContent || !rect?.width || !rect?.height)) return null;
      node.kids = [];
    }
    return tag === 'slot' ? node.kids : node;
  }

  // ---------- Public API ----------

  W.capture = ({ root, region = null, styles = false }) => {
    const st = { count: 0, truncated: false, defaults: styles ? defaultStyles() : null };
    try {
      const out = [];
      walkNode(root, { full: !region, clip: region, inTable: false, vals: null }, st, out);
      const ir = out.length === 1 && out[0].tag ? out[0] : { tag: 'div', attrs: {}, display: 'block', kids: out };
      return { ir, truncated: st.truncated };
    } finally {
      st.defaults?.dispose();
    }
  };

  W.describe = el => {
    let s = el.localName;
    if (el.id) s += `#${el.id}`;
    const cls = [...el.classList].filter(c => !HASHED_CLASS.test(c)).slice(0, 2);
    if (cls.length) s += `.${cls.join('.')}`;
    return s;
  };

  W.cleanUrl = cleanUrl;
  W.regionRoot = regionRoot;
  W.shadowOf = shadowOf;
})();
